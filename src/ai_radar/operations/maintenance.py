"""Daily maintenance: staleness, queue review, cache pruning, quota report.

This is the job that answers "is the system actually healthy?", independently of
whether individual runs succeeded. It reads stored state, never live feeds.
"""

from __future__ import annotations

from typing import Any

from ..notifications import TelegramClient, TelegramError
from ..utils.logging import get_logger
from ..utils.timeutil import utcnow
from .heartbeat import HeartbeatReporter

logger = get_logger(__name__)


class MaintenanceService:
    def __init__(
        self,
        *,
        repository,
        heartbeat: HeartbeatReporter,
        telegram: TelegramClient | None,
        stale_after_minutes: int = 150,
    ) -> None:
        self._repo = repository
        self._heartbeat = heartbeat
        self._telegram = telegram
        self._stale_after = stale_after_minutes

    async def run(self, *, notify: bool = True, prune: bool = True) -> dict[str, Any]:
        check = await self._heartbeat.check()
        problems: list[str] = list(check["problems"])

        pruned = {"analysis_cache": 0, "provider_usage": 0}
        if prune:
            pruned["analysis_cache"] = await self._repo.prune_analysis_cache()
            pruned["provider_usage"] = await self._repo.prune_provider_usage()

        provider_health = await self._repo.provider_health(hours=24)
        # free.ai is budget-capped by tokens, not by request count, so it needs
        # both figures to be actionable: calls today and the rolling 24 h spend
        # the adapter enforces.
        quota = {
            provider: await self._repo.quota_used_today(provider)
            for provider in ("freeai", "gemini", "groq")
        }
        freeai_tokens = await self._repo.provider_tokens_last_24h("freeai")
        delivery_counts = await self._repo.delivery_counts()
        overview = check["overview"]

        result = {
            "checked_at": utcnow().isoformat(),
            "stale": check["stale"],
            "problems": problems,
            "pruned": pruned,
            "provider_health": provider_health,
            "quota_today": quota,
            "freeai_tokens_24h": freeai_tokens,
            "deliveries": delivery_counts,
            "overview": {
                key: (value.isoformat() if hasattr(value, "isoformat") else value)
                for key, value in overview.items()
            },
        }

        reported = False
        if problems and notify and self._telegram is not None and self._telegram.configured:
            reported = await self._report(problems, delivery_counts)

        await self._repo.set_state(
            "maintenance", {**result, "notified": reported}
        )
        logger.info(
            "maintenance_complete",
            problems=len(problems),
            stale=check["stale"],
            notified=reported,
        )
        result["notified"] = reported
        return result

    async def _report(self, problems: list[str], delivery_counts: dict[str, int]) -> bool:
        lines = ["<b>AI Radar — health check</b>", ""]
        lines.extend(f"• {problem}" for problem in problems[:8])
        pending = delivery_counts.get("PENDING", 0) + delivery_counts.get("RETRY_WAIT", 0)
        if pending:
            lines.append(f"• {pending} alert(s) queued for delivery")
        unknown = delivery_counts.get("UNKNOWN", 0)
        if unknown:
            lines.append(
                f"• {unknown} delivery outcome(s) unknown — inspect the deliveries table before retrying"
            )
        lines.append("")
        lines.append("<i>This message is generated by the maintenance workflow, not a research run.</i>")
        try:
            assert self._telegram is not None
            await self._telegram.send_message("\n".join(lines))
            return True
        except TelegramError as exc:
            logger.error("maintenance_report_failed", kind=exc.kind, error=str(exc))
            return False
